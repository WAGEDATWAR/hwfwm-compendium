"""Regenerate wiki-tier lists: runs wiki_lists.py, rewrites 03_Magic_and_Adventuring/Wiki_Reference_Lists.md and the
wiki gods table in 02_Cosmology_and_Powers/Gods_and_Churches.md."""
import os, re, subprocess, sys, io

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")
HERE = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.abspath(os.path.join(HERE, "..", ".."))
subprocess.run([sys.executable, os.path.join(HERE, "wiki_lists.py")], check=True, cwd=HERE)
rd = lambda f: open(os.path.join(HERE, f), encoding="utf-8").read().strip()
mon = rd("wiki_monster_tables.md").split("\n")


def mlist(l):
    t, rest = l.split(": ", 1)
    return t, [x.strip("* ").replace("King - ", "") for x in rest.split("; ")]


monsters = "\n".join("- **%s**: %s" % (t.replace(" Monsters", ""), ", ".join(v)) for t, v in map(mlist, mon))
doc = """# Wiki Reference Lists

Status: Draft (wiki tier: these lists come from the fan wiki's pages, copied into this compendium to fill gaps that the book text does not list in one place; entries the books also state carry the first book line in the last column, and the book text wins wherever the two differ)
Spoiler level: 3 (the lists name late-series essences, confluences and users)
Valid from: Book 1
Valid through: Book 13
Sources: fan wiki (wiki); `src/Source_Text/` for the cross-references in the last column
Related: 00_Magic_Overview.md, Essences.md, Essence_Catalogue.md, Confluences.md, Awakening_Stones.md, Monsters.md, ../02_Cosmology_and_Powers/Gods_and_Churches.md

These lists use the project's source hierarchy: Book Files > Chapter Summaries > Wiki. The wiki is the lowest tier, but its lists of essences, confluences, stones and monsters are the only place those items are gathered, so they are kept here with their tier marked. A cell in the "In the book text" column gives the first place the chapter files use the name in a phrase like "<name> essence"; a blank cell means no such phrase was found, not that the wiki is wrong. Rarity and ability data come from the wiki's essence pages and may be incomplete or out of date. The lists are regenerated by `src/TEMP_scratchpad_recovery/compose_wiki.py`.

## 1. Essences (wiki)

The wiki lists the essences below by rarity, with the abilities and users it records for each. Rarity is one of Common, Uncommon, Rare, Epic and Legendary (wiki); the books use the same five stages (see `Awakening_Stones.md`).

""" + rd("wiki_essence_table.md") + """

## 2. Confluences and their known combinations (wiki)

The wiki's table of confluence essences (wiki), each with the combinations of three essences it records and the holders it names. The books state that a combination gives a fixed confluence until Book 11 (see `Confluences.md`).

""" + rd("wiki_confluence_table.md") + """

## 3. Awakening stones (wiki)

The wiki's stone pages (wiki), with the rarity shown on the item screen where one is recorded and the abilities the wiki credits to each stone.

""" + rd("wiki_stone_table.md") + """

## 4. Monsters by rank (wiki)

The wiki's rank pages list these monsters (wiki). The bestiary in `Monsters.md` gives the ranks the book text states.

""" + monsters + "\n"
open(os.path.join(BASE, "03_Magic_and_Adventuring", "Wiki_Reference_Lists.md"), "w", encoding="utf-8").write(doc)
g = rd("wiki_gods_table.md")
tbl, minor = g.split("\n\nMINOR: ")
p = os.path.join(BASE, "02_Cosmology_and_Powers", "Gods_and_Churches.md")
s = open(p, encoding="utf-8").read()
i = s.index("| God (wiki list)")
j = s.index("\n\n", i)
s = s[:i] + tbl + s[j:]
s = re.sub(r"The fan wiki records the 43 gods below.*?\n\n", lambda m: "The fan wiki records the 43 gods below with the chapter of first mention (wiki). Its chapter numbers use the wiki's own numbering, not the chapter files of this project. The last column gives the first place the book text mentions the god's church, temple or priests, where found; the book text wins where the two differ. The wiki also lists minor \"profession\" gods: " + minor + " (wiki); and says evil or hidden gods such as Deceit, Destruction, Pain and Undeath are worshipped in secret (wiki).\n\n", s, count=1, flags=re.S)
open(p, "w", encoding="utf-8").write(s)
print("done")
