"""Generate the file index of each folder overview from the folder contents, so the lists cannot drift.

For every overview listed in OVERVIEWS this tool rewrites the block between
    <!-- files:start -->  and  <!-- files:end -->
with one line per document in the folder (and its subfolders): link, spoiler level and the first sentence of the
document's Summary; group files also list the names of their "###" entries. Text outside the markers is hand-written
and never touched. If an overview has no markers yet, a "Files in this folder (generated)" section is appended.

Usage: python3 src/tools/overviews.py          rewrite the blocks
       python3 src/tools/overviews.py --check  report overviews whose block is out of date (used by lint.py)
"""
import os, re, sys, io

HERE = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.abspath(os.path.join(HERE, "..", ".."))
START, END = "<!-- files:start -->", "<!-- files:end -->"

# overview path -> folder it indexes (relative to BASE)
OVERVIEWS = {
    "02_Cosmology_and_Powers/00_Cosmology_Overview.md": "02_Cosmology_and_Powers",
    "03_Magic_and_Adventuring/00_Magic_Overview.md": "03_Magic_and_Adventuring",
    "04_Peoples_and_Cultures/00_Peoples_Overview.md": "04_Peoples_and_Cultures",
    "05_Organisations/00_Organisations_Overview.md": "05_Organisations",
    "06_Places/00_Places_Overview.md": "06_Places",
    "06_Places/Astral_Spaces/00_Astral_Overview.md": "06_Places/Astral_Spaces",
    "06_Places/Earth/00_Earth_Overview.md": "06_Places/Earth",
    "07_Characters/00_Characters_Overview.md": "07_Characters",
    "08_History_and_Timeline/00_History_Overview.md": "08_History_and_Timeline",
    "09_Items_and_Artefacts/00_Items_Overview.md": "09_Items_and_Artefacts",
    "10_Roleplay_Support/00_Roleplay_Overview.md": "10_Roleplay_Support",
    "Appendices/00_Appendices_Overview.md": "Appendices",
}


def read(rel):
    return open(os.path.join(BASE, *rel.split("/")), encoding="utf-8").read()


def meta(rel):
    text = read(rel)
    m = re.search(r"^# (.+)$", text, re.M)
    title = m.group(1).strip() if m else rel
    m = re.search(r"^Spoiler level:\s*(.*)$", text, re.M)
    lvl = m.group(1).strip() if m else "?"
    lvl = re.split(r"[;(]| for ", lvl)[0].strip() or lvl
    summ = ""
    m = re.search(r"^## 1\. [^\n]*\n+(.+?)(?:\n\n|\Z)", text, re.S | re.M)
    if m:
        para = re.sub(r"\s+", " ", m.group(1)).strip()
        if not para.startswith(("|", "-", "#")) and not re.match(r"\d+\.", para):
            sm = re.match(r"(.+?[.!?])(\s|$)", para)
            summ = (sm.group(1) if sm else para)
            if len(summ) > 160:
                summ = summ[:157].rsplit(" ", 1)[0] + "..."
    names = re.findall(r"^### (.+)$", text, re.M) if "Minor_" in rel else []
    return title, lvl, summ, names


def block(overview, folder):
    root = os.path.join(BASE, *folder.split("/"))
    groups = {}
    for dp, dn, fn in os.walk(root):
        dn[:] = sorted(dn)
        for f in sorted(fn):
            if not f.endswith(".md"):
                continue
            rel = os.path.relpath(os.path.join(dp, f), BASE).replace("\\", "/")
            if rel == overview:
                continue
            sub = os.path.relpath(dp, root).replace("\\", "/")
            groups.setdefault("" if sub == "." else sub, []).append(rel)
    ov_dir = os.path.dirname(overview)
    out = []
    for sub in sorted(groups, key=lambda x: (x != "", x)):
        if sub:
            out += ["", "**%s/**" % sub, ""]
        for rel in sorted(groups[sub], key=lambda r: (not os.path.basename(r).startswith("00_"), os.path.basename(r).lower())):
            title, lvl, summ, names = meta(rel)
            link = os.path.relpath(os.path.join(BASE, *rel.split("/")), os.path.join(BASE, *ov_dir.split("/"))).replace("\\", "/")
            line = "- [%s](%s) (spoiler level %s)" % (title, link, lvl)
            if summ:
                line += ": " + summ
            if names and len(names) >= 2:
                line += " Entries: " + ", ".join(names[:14]) + (" ..." if len(names) > 14 else "") + "."
            out.append(line)
    return "\n".join([START, "<!-- generated by src/tools/overviews.py; do not edit by hand -->", ""] + out + ["", END])


def apply(overview, folder, check=False):
    path = os.path.join(BASE, *overview.split("/"))
    if not os.path.exists(path):
        return None
    text = open(path, encoding="utf-8").read()
    new_block = block(overview, folder)
    if START in text and END in text:
        i, j = text.index(START), text.index(END) + len(END)
        new_text = text[:i] + new_block + text[j:]
    else:
        new_text = text.rstrip("\n") + "\n\n## Files in this folder (generated)\n\n" + new_block + "\n"
    if new_text == text:
        return False
    if not check:
        open(path, "w", encoding="utf-8").write(new_text)
    return True


def run(check=False):
    changed = []
    for ov, folder in OVERVIEWS.items():
        r = apply(ov, folder, check)
        if r:
            changed.append(ov)
    return changed


if __name__ == "__main__":
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")
    chk = "--check" in sys.argv
    ch = run(chk)
    print(("out of date: " if chk else "rewritten: ") + (", ".join(ch) if ch else "none"))
