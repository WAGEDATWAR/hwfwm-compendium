"""List facts cited from the same book line in three or more documents (build plan item 5.7).

Reads register_new.json (written by build_register.py) and groups rows by their first reference. Clusters spread over three or more
documents are candidates for a single home file with pointers elsewhere. Many are deliberate (folder overviews, power-set files,
derived quick-reference sheets, timelines), so the report is a triage list and not a to-do list. Writes src/tools/redundancy_report.md.

Usage: python3 src/tools/redundancy_report.py
"""
import json, os, collections, io, sys

HERE = os.path.dirname(os.path.abspath(__file__))


def main():
    rows = json.load(open(os.path.join(HERE, "register_new.json"), encoding="utf-8"))
    by = collections.defaultdict(list)
    for x in rows:
        if not x["refs"] or x["doc"].startswith(("Appendices", "08_History", "10_Roleplay")):
            continue
        by[tuple(x["refs"][0][:4])].append(x)
    cl = [(k, v) for k, v in by.items() if len({y["doc"] for y in v}) >= 3]
    cl.sort(key=lambda kv: (-len({y["doc"] for y in kv[1]}), kv[0]))
    L = ["# Redundancy report", "",
         "Generated by `src/tools/redundancy_report.py` (build plan item 5.7). %d clusters: a book line cited by three or more documents. Timelines, roleplay files and appendices are left out. Many clusters are deliberate; see the tool's note." % len(cl), ""]
    for k, v in cl:
        docs = sorted({y["doc"] for y in v})
        L.append("- B%d Ch%d L%d-%d (%d documents): %s | %s" % (k + (len(docs), v[0]["claim"][:100].replace("\n", " "), ", ".join(d.split("/")[-1][:-3] for d in docs))))
    open(os.path.join(HERE, "redundancy_report.md"), "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
    print("%d clusters (see src/tools/redundancy_report.md)" % len(cl))


if __name__ == "__main__":
    main()
