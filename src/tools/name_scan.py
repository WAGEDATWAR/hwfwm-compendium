"""Missing-name scan (build plan item 1.8).

Finds capitalised words that occur often in the chapter files but nowhere in the compendium documents, so that
characters, places and terms the compendium has not yet covered show up.

A word counts when it is capitalised in the middle of a sentence (after a lower-case word, comma, semicolon or colon,
or after an opening quote that follows such a word), which filters out words that are only capitalised because they
start a sentence. A word is "covered" if it appears (case-insensitive, whole word) in any compendium .md file
outside src/ and outside the generated Source_Register.md and Source_Map.md.

Usage: python3 src/tools/name_scan.py [MIN_COUNT] [--samples] [--index]
       MIN_COUNT defaults to 15. --samples prints one sample line for each word. --index counts a word as covered
       only if it appears in Appendices/Name_Index.md or Glossary.md (a stricter test than any document).
Writes the list to src/tools/name_scan_report.md as well.
"""
import os, re, sys, io, collections

HERE = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.abspath(os.path.join(HERE, "..", ".."))
ST = os.path.join(BASE, "src", "Source_Text")
SKIP_DOCS = {"Appendices/Source_Register.md", "Appendices/Source_Map.md"}
MID = re.compile(r"(?<=[a-z,;:] )([A-Z][a-z]{2,})\b")
# words that are capitalised mid-sentence for reasons other than being names
IGNORE = set("""Book Chapter The This That There These Those What When Where Why How Who Which Then Thanks Yes No
Mr Mrs Miss Ms Sir Lady Lord Madam Doctor Director Captain General Commander Prince Princess King Queen Duke Your
Highness Majesty Excellency Master Mistress Professor Father Mother Brother Sister Uncle Aunt Nana Nanna Grandmother
Grandfather Monday Tuesday Wednesday Thursday Friday Saturday Sunday January February March April May June July August
September October November December God Gods Goddess Good Great Little Old New First Second Third Last Next
English Australian American British Chinese Japanese Russian French Italian Swiss Indian African Asian European Earth
Pallimustus Mum Americans Batman Voltron Airwolf""".split())


def docs_text(index_only=False):
    if index_only:
        names = ("Name_Index.md", "Glossary.md")
        return "\n".join(open(os.path.join(BASE, "Appendices", f), encoding="utf-8").read() for f in names).lower()
    parts = []
    for root, dirs, files in os.walk(BASE):
        dirs[:] = [d for d in dirs if d not in ("src", ".git")]
        for f in files:
            if not f.endswith(".md"):
                continue
            rel = os.path.relpath(os.path.join(root, f), BASE).replace("\\", "/")
            if rel in SKIP_DOCS:
                continue
            parts.append(open(os.path.join(root, f), encoding="utf-8").read())
    return "\n".join(parts).lower()


def scan(min_count=15, index_only=False):
    corpus = docs_text(index_only)
    counts = collections.Counter()
    books = collections.defaultdict(collections.Counter)
    sample = {}
    for bd in sorted(os.listdir(ST)):
        if not bd.startswith("Book_"):
            continue
        b = int(bd.split("_")[1])
        for fn in sorted(os.listdir(os.path.join(ST, bd))):
            m = re.match(r"Ch_(\d+)_", fn)
            if not m:
                continue
            ch = int(m.group(1))
            lines = open(os.path.join(ST, bd, fn), encoding="utf-8").read().split("\n")
            for i, ln in enumerate(lines, 1):
                for w in MID.findall(ln):
                    if w in IGNORE:
                        continue
                    counts[w] += 1
                    books[w][b] += 1
                    sample.setdefault(w, "Book %d, Ch%d L%d: %s" % (b, ch, i, ln.strip()[:150]))
    out = []
    for w, n in counts.most_common():
        if n < min_count:
            break
        if re.search(r"\b" + re.escape(w.lower()) + r"\b", corpus):
            continue
        bs = ", ".join("B%d x%d" % (k, books[w][k]) for k in sorted(books[w]))
        out.append((w, n, bs, sample[w]))
    return out


if __name__ == "__main__":
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    mc = int(args[0]) if args else 15
    res = scan(mc, "--index" in sys.argv)
    lines = ["# Missing-name scan", "",
             "Generated by `src/tools/name_scan.py`: capitalised words that occur %d or more times mid-sentence in the chapter files and are not covered (%s)." % (mc, "not in the Name Index or Glossary" if "--index" in sys.argv else "not in any compendium document"), ""]
    if not res:
        lines.append("None.")
    for w, n, bs, s in res:
        lines.append("- **%s** (%d; %s): %s" % (w, n, bs, s))
    open(os.path.join(HERE, "name_scan_report.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    for w, n, bs, s in res:
        print("%s\t%d\t%s" % (w, n, bs))
        if "--samples" in sys.argv:
            print("    " + s)
    print(len(res), "uncovered words")
