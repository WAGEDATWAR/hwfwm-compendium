"""Register delta: compare the rows of the previous build_register.py run with the current run.

Rows are matched on (document, claim text). A removed row and an added row in the same document whose claims
overlap by 45 percent or more are reported as an edit rather than as a removal plus an addition.
Writes src/tools/register_delta.md and returns a one-line summary.
"""
import os, re, collections

HERE = os.path.dirname(os.path.abspath(__file__))
CAP = 80


def key(r):
    return (r["doc"], re.sub(r"\s+", " ", r["claim"].strip().lower())[:200])


def words(t):
    return set(re.findall(r"[a-z]{4,}", t.lower()))


def compare(prev, cur):
    pm, cm = collections.defaultdict(list), collections.defaultdict(list)
    for r in prev:
        pm[key(r)].append(r)
    for r in cur:
        cm[key(r)].append(r)
    removed, added, changed = [], [], []
    for k in set(pm) | set(cm):
        a, b = pm.get(k, []), cm.get(k, [])
        for i in range(max(len(a), len(b))):
            if i >= len(a):
                added.append(b[i])
            elif i >= len(b):
                removed.append(a[i])
            elif a[i]["check"] != b[i]["check"]:
                changed.append((a[i], b[i]))
    # pair removed with added in the same document as edits
    edits = []
    by_doc = collections.defaultdict(list)
    for r in added:
        by_doc[r["doc"]].append(r)
    still_removed = []
    for r in removed:
        w = words(r["claim"])
        best, bj = None, 0.0
        for c in by_doc[r["doc"]]:
            cw = words(c["claim"])
            if not w or not cw:
                continue
            j = len(w & cw) / len(w | cw)
            if j > bj:
                best, bj = c, j
        if best is not None and bj >= 0.45:
            by_doc[r["doc"]].remove(best)
            edits.append((r, best))
        else:
            still_removed.append(r)
    added = [c for lst in by_doc.values() for c in lst]
    return still_removed, added, edits, changed


def short(r):
    return "`%s`: %s" % (r["doc"], r["claim"].strip().replace("\n", " ")[:120])


def report(prev, cur):
    removed, added, edits, changed = compare(prev, cur)
    new_weak = [r for r in added if r["check"] == "weak"] + [b for a, b in edits + changed if b["check"] == "weak" and a["check"] != "weak"]
    gone_weak = [a for a, b in edits + changed if a["check"] == "weak" and b["check"] != "weak"] + [r for r in removed if r["check"] == "weak"]
    summary = "delta: %d rows now (was %d): +%d added, -%d removed, %d edited, %d regraded; weak: +%d new, -%d cleared" % (
        len(cur), len(prev), len(added), len(removed), len(edits), len(changed), len(new_weak), len(gone_weak))
    L = ["# Register delta", "", "Generated by `src/tools/delta.py` at the end of each `build_register.py` run: the rows changed since the previous run (the previous `register_new.json`).", "", summary, ""]

    def block(title, items, fmt):
        L.append("## %s (%d)" % (title, len(items)))
        L.append("")
        for it in items[:CAP]:
            L.append("- " + fmt(it))
        if len(items) > CAP:
            L.append("- ... %d more" % (len(items) - CAP))
        if not items:
            L.append("None.")
        L.append("")

    block("New weak rows", new_weak, short)
    block("Weak rows cleared", gone_weak, short)
    block("Regraded", changed, lambda t: "%s (%s to %s)" % (short(t[1]), t[0]["check"], t[1]["check"]))
    block("Added", added, lambda r: "%s [%s]" % (short(r), r["check"]))
    block("Removed", removed, short)
    block("Edited", edits, lambda t: "%s [%s to %s]" % (short(t[1]), t[0]["check"], t[1]["check"]))
    open(os.path.join(HERE, "register_delta.md"), "w", encoding="utf-8").write("\n".join(L))
    return summary
